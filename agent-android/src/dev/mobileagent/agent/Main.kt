package dev.mobileagent.agent

import dev.mobileagent.agent.codec.Protocol
import kotlin.system.exitProcess

/**
 * Entry point of the resident agent, started by `app_process` as the shell user:
 *
 *     CLASSPATH=<jar> app_process / dev.mobileagent.agent.Main [--version]
 *     MOBILE_AGENT_TOKEN=<token> CLASSPATH=<jar> app_process / dev.mobileagent.agent.Main serve --socket <name> [options]
 *
 * With `--version` or no arguments it prints [BANNER] as one line and exits 0.
 * `serve` runs the agent until the host asks it to stop (see [Options]).
 * Any other first argument prints `unknown argument` to stderr and exits 2.
 */
object Main {
    /** Version banner; [BuildConfig.VERSION] is generated by build.sh from the VERSION file. */
    const val BANNER = "mobile-agent-android ${BuildConfig.VERSION} protocol=${Protocol.VERSION}"

    /** The agent's name and version, as its hello carries them. */
    const val AGENT = "mobile-agent-android ${BuildConfig.VERSION}"

    @JvmStatic
    fun main(args: Array<String>) {
        val code = run(args)
        System.out.flush()
        System.err.flush()
        // Framework threads (binder, handler threads) would keep the VM alive otherwise.
        exitProcess(code)
    }

    private fun run(args: Array<String>): Int {
        if (args.isEmpty() || (args.size == 1 && args[0] == "--version")) {
            println(BANNER)
            return 0
        }
        if (args.size == 3 && args[0] == "connect-check" && args[1] == "--socket") return connectCheck(args[2])
        if (args[0] != "serve") {
            System.err.println("unknown argument: ${args[0]}")
            return 2
        }
        val options = try {
            Options.parse(args.copyOfRange(1, args.size), System.getenv(Options.TOKEN_VARIABLE))
        } catch (e: UsageException) {
            System.err.println("usage: ${Options.USAGE}")
            System.err.println(e.message)
            return 2
        }
        return Server(options).run()
    }
}

/**
 * `connect-check --socket NAME`: connects to an agent's abstract socket as
 * whatever user runs it and prints how many bytes arrived within 2 s, so a
 * test can show that a peer other than the shell user gets no hello.
 */
private fun connectCheck(name: String): Int {
    val socket = android.net.LocalSocket()
    try {
        socket.connect(android.net.LocalSocketAddress(name, android.net.LocalSocketAddress.Namespace.ABSTRACT))
    } catch (e: java.io.IOException) {
        println("connect-check uid=${android.os.Process.myUid()} error=${e.message?.replace(' ', '_')}")
        return 1
    }
    socket.soTimeout = 2000
    var total = 0
    try {
        val buf = ByteArray(4096)
        while (true) {
            val n = socket.inputStream.read(buf)
            if (n < 0) break
            total += n
        }
    } catch (e: java.io.IOException) {
        // The read timeout: nothing more arrived.
    }
    socket.close()
    println("connect-check uid=${android.os.Process.myUid()} bytes=$total")
    return 0
}

class UsageException(message: String) : Exception(message)

/**
 * Options of `serve`. The per-launch token comes from the environment
 * variable [TOKEN_VARIABLE], so it never appears in the process listing.
 */
class Options(
    /** Name of the abstract socket to listen on, unique per launch. */
    @JvmField val socket: String,
    /** The per-launch token the hello carries. */
    @JvmField val token: String?,
    /** Stop a known automation client that holds UI automation instead of reporting the conflict. */
    @JvmField val force: Boolean,
    /** Longest wait for an active window after taking the role. */
    @JvmField val windowWaitMs: Long,
) {
    companion object {
        const val TOKEN_VARIABLE = "MOBILE_AGENT_TOKEN"
        const val USAGE = "serve --socket NAME [--force] [--window-wait-ms N]"
        private val SOCKET_NAME = Regex("[A-Za-z0-9._-]{1,100}")

        fun parse(args: Array<String>, token: String?): Options {
            var socket: String? = null
            var force = false
            var windowWaitMs = 2_000L
            var i = 0
            fun value(name: String): String {
                if (i + 1 >= args.size) throw UsageException("$name needs a value")
                i++
                return args[i]
            }
            fun millis(name: String): Long =
                value(name).toLongOrNull()?.takeIf { it >= 0 } ?: throw UsageException("$name takes a number of milliseconds")
            while (i < args.size) {
                when (val arg = args[i]) {
                    "--socket" -> socket = value(arg)
                    "--force" -> force = true
                    "--window-wait-ms" -> windowWaitMs = millis(arg)
                    else -> throw UsageException("unknown argument: $arg")
                }
                i++
            }
            val name = socket ?: throw UsageException("--socket is required")
            if (!SOCKET_NAME.matches(name)) throw UsageException("--socket takes 1 to 100 of A-Z a-z 0-9 . _ -")
            return Options(name, token?.takeIf { it.isNotEmpty() }, force, windowWaitMs)
        }
    }
}

/** Lines on stdout, where the process that started the agent reads them. */
object Out {
    @Synchronized
    fun line(text: String) {
        println(text)
        System.out.flush()
    }
}
