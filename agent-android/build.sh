#!/usr/bin/env bash
# Builds the resident Android agent into dist/mobile-agent-android.jar without Gradle:
#
#   1. VERSION becomes the constant BuildConfig.VERSION in a generated source.
#   2. kotlinc compiles src/ and that source against the platform android.jar.
#   3. d8 dexes the classes together with the Kotlin stdlib into one classes.dex.
#   4. classes.dex becomes the jar's only member, which app_process accepts on CLASSPATH.
#
# Progress goes to stderr. The last two lines on stdout are the jar path and the
# classes.dex size in bytes.
#
# ANDROID_HOME  Android SDK root, default $HOME/Library/Android/sdk. Needs
#               platforms/android-36 and build-tools; d8 comes from the newest build-tools.
# KOTLIN_HOME   Kotlin compiler home, default the install behind kotlinc on PATH.
#               Both kotlinc and kotlin-stdlib.jar come from it.
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
android_home="${ANDROID_HOME:-$HOME/Library/Android/sdk}"
platform_jar="$android_home/platforms/android-36/android.jar"
min_api=26
jvm_target=17
out="$here/out"
jar="$here/dist/mobile-agent-android.jar"

die() {
  printf 'build.sh: %s\n' "$*" >&2
  exit 1
}

log() {
  printf '==> %s\n' "$*" >&2
}

version="$(<"$here/VERSION")"
[[ $version =~ ^[0-9]+\.[0-9]+\.[0-9]+(-[0-9A-Za-z.-]+)?$ ]] ||
  die "VERSION must hold one semantic version such as 0.1.0, found '$version'"

[[ -f $platform_jar ]] || die "no platform jar at $platform_jar; install platforms;android-36 or set ANDROID_HOME"

# d8 comes from the SDK's newest build-tools, not from PATH, where the
# cmdline-tools or Homebrew copies may be a different release.
[[ -d $android_home/build-tools ]] || die "no build-tools in $android_home; install a build-tools package"
build_tools="$(ls -1 "$android_home/build-tools" | sort -V | tail -n 1)"
d8="$android_home/build-tools/$build_tools/d8"
[[ -x $d8 ]] || die "no d8 at $d8"

if [[ -n ${KOTLIN_HOME:-} ]]; then
  kotlin_home="$KOTLIN_HOME"
else
  kotlinc_path="$(command -v kotlinc)" || die "kotlinc is not on PATH; install Kotlin or set KOTLIN_HOME"
  kotlinc_path="$(readlink -f "$kotlinc_path")"
  # A mise shim resolves to the mise binary rather than the compiler, so ask mise.
  if [[ $(basename "$kotlinc_path") != kotlinc ]] && command -v mise >/dev/null; then
    kotlinc_path="$(mise which kotlinc)" || die "mise does not provide kotlinc; set KOTLIN_HOME"
    kotlinc_path="$(readlink -f "$kotlinc_path")"
  fi
  kotlin_home="$(dirname "$(dirname "$kotlinc_path")")"
fi
kotlinc="$kotlin_home/bin/kotlinc"
stdlib="$kotlin_home/lib/kotlin-stdlib.jar"
[[ -x $kotlinc && -f $stdlib ]] ||
  die "no bin/kotlinc and lib/kotlin-stdlib.jar under $kotlin_home; set KOTLIN_HOME to a Kotlin compiler home"

jar_tool="$(command -v jar)" || die "jar is not on PATH; install a JDK"

rm -rf "$out"
gen="$out/gen/dev/mobileagent/agent"
mkdir -p "$gen" "$out/classes" "$out/dex" "$(dirname "$jar")"
cat >"$gen/BuildConfig.kt" <<KOTLIN
// Generated by build.sh from VERSION.
package dev.mobileagent.agent

internal object BuildConfig {
    const val VERSION = "$version"
}
KOTLIN

sources=()
while IFS= read -r -d '' file; do
  sources+=("$file")
done < <(find "$here/src" "$out/gen" -name '*.kt' -print0)

log "kotlinc: ${#sources[@]} sources, jvm-target $jvm_target, against android-36 (from $kotlin_home)"
# -no-jdk and -no-reflect leave android.jar and the stdlib as the only APIs in
# scope, so code that would not link on a device does not compile either.
"$kotlinc" -jvm-target "$jvm_target" -no-jdk -no-reflect -Werror \
  -classpath "$platform_jar" -d "$out/classes" "${sources[@]}"

# d8 takes class files, not directories.
classes=()
while IFS= read -r -d '' file; do
  classes+=("$file")
done < <(find "$out/classes" -name '*.class' -print0)
((${#classes[@]} > 0)) || die "kotlinc produced no class files"

log "d8 (build-tools $build_tools): ${#classes[@]} classes and $(basename "$stdlib"), min-api $min_api"
if ! "$d8" --release --min-api "$min_api" --lib "$platform_jar" --output "$out/dex" \
  "${classes[@]}" "$stdlib" >"$out/d8.log" 2>&1; then
  cat "$out/d8.log" >&2
  die "d8 failed"
fi
# A D8 released before the Kotlin compiler cannot parse the newer kotlin.Metadata
# and reports it for every stdlib class. Only kotlin-reflect reads that metadata
# and the agent does not ship it, so those diagnostics are counted rather than
# shown. Every other diagnostic is shown; out/d8.log keeps the full output.
awk -v logfile="$out/d8.log" '
  function flush() {
    if (block ~ /[Kk]otlin metadata|kotlin\.Metadata/) metadata++
    else if (block != "") printf "%s", block
    block = ""
  }
  /^(Error|Warning|Info)( in |: )/ { flush() }
  { block = block $0 "\n" }
  END {
    flush()
    if (metadata) printf "==> d8: %d diagnostics about Kotlin metadata newer than this D8 reads (full output: %s)\n", metadata, logfile
  }
' "$out/d8.log" >&2

[[ -f $out/dex/classes.dex ]] || die "d8 produced no classes.dex"
[[ ! -e $out/dex/classes2.dex ]] || die "d8 split the agent across several dex files; it must fit in one classes.dex"

rm -f "$jar"
"$jar_tool" --create --no-manifest --file "$jar" -C "$out/dex" classes.dex

dex_bytes="$(wc -c <"$out/dex/classes.dex" | tr -d ' ')"
printf '%s\n' "$jar"
printf 'classes.dex %s bytes\n' "$dex_bytes"
